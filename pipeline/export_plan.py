"""Write agendamento/plano/plano.csv and plano.md: every video and Short with its title, publish time, files and YouTube status.
Meant for scheduling by hand in YouTube Studio (or by an agent): nothing already on YouTube is listed as pending."""
import csv, datetime as dt, json, os, pathlib
from zoneinfo import ZoneInfo

NY = ZoneInfo("America/New_York")
SLOTS_NY = ["18:00", "15:00", "21:00"]
REPO = "viniciushoscher-ctrl/machine-reverse"
cal = json.load(open("agendamento/calendar.json"))
state = json.load(open("agendamento/youtube-state.json")) if os.path.exists("agendamento/youtube-state.json") else {}
rows = []
for day in cal:
    items = [("long", day.get("long"), None)] + [("short", v, s) for v, s in day.get("shorts", [])]
    times = day.get("times") or SLOTS_NY
    for slot, (kind, v, s) in enumerate(items):
        if not v: continue
        mf = pathlib.Path(f"agendamento/meta/video{v:02d}.json")
        if not mf.exists(): continue
        m = json.loads(mf.read_text())
        hh, mm = map(int, times[min(slot, len(times) - 1)].split(":"))
        at = dt.datetime.fromisoformat(day["date"]).replace(hour=hh, minute=mm, tzinfo=NY)
        if kind == "long":
            key, fname, title, desc = f"v{v:02d}", f"video{v:02d}.mp4", m["title"], m["description"]
            thumb = f"agendamento/thumbs/video{v:02d}.jpg"
        else:
            sm = next((x for x in m["shorts"] if x["file"] == f"short{s}.mp4"), None)
            if not sm: continue
            key, fname, title, desc, thumb = f"v{v:02d}-s{s}", sm["file"], sm["title"], sm["description"], ""
        st = state.get(key, {})
        status = "ON YOUTUBE (scheduled)" if st.get("id") else ("skipped (slot passed)" if st.get("skipped") else "pending upload")
        rows.append({"key": key, "type": kind, "video": v, "publish_new_york": at.strftime("%Y-%m-%d %H:%M"),
                     "publish_utc": at.astimezone(dt.timezone.utc).strftime("%Y-%m-%d %H:%M"), "title": title,
                     "status": status, "youtube_id": st.get("id", ""),
                     "file": fname, "file_url": f"https://github.com/{REPO}/releases/download/video{v:02d}/{fname}",
                     "thumbnail": thumb, "description_file": f"agendamento/meta/video{v:02d}.json"})
rows.sort(key=lambda r: r["publish_utc"])
out = pathlib.Path("agendamento/plano"); out.mkdir(exist_ok=True)
with open(out / "plano.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
md = ["# Publishing plan (generated by pipeline/export_plan.py)", "",
      "Times are America/New_York. Status ON YOUTUBE means already uploaded and scheduled by the API robot: do not upload it again.",
      "Title and description of each video are in the meta file (`description` field); Shorts titles are in its `shorts` list.", "",
      "| Publish (NY) | Type | Video | Title | Status | File |", "|---|---|---|---|---|---|"]
for r in rows:
    md.append(f"| {r['publish_new_york']} | {r['type']} | {r['video']:02d} | {r['title']} | {r['status']} | [{r['file']}]({r['file_url']}) |")
(out / "plano.md").write_text("\n".join(md) + "\n")
print(len(rows), "rows;", sum(r["status"].startswith("ON") for r in rows), "already on YouTube")
